"""
Cosine-sim check for the epoch_011 fully fine-tuned CLIP checkpoint (both towers,
checkpoints_clip_full_fine-tuned_with_subopt_data/): does the CLIP image embedding of a single
real rollout frame sit closer to the true scene statement than to all 448 guaranteed-false
statements at that same timestep?

Frame: timestep 200 of
  rollouts_5_per/expert+subopt_iters1000_exec8_with_pkls/epoch11/epoch11_rollout0_success.mp4
True statement: "The green cube is touching the blue moon. The peg is touching the green cube."

Ground truth for the 448 negatives is NOT assumed -- it is read from this rollout's own saved
pybullet state at t=200 (epoch11_rollout0_pybullet_states.pkl), restored via the real LangTable
env (same pattern as dump_pybullet_state_frames.py / oracle_vs_mppi_charts.py), then run through
cache_zhard.py's own build_hard_neg_data() unmodified -- so the negatives are generated by
exactly the same logic used at training/caching time, not reimplemented here.

Run:
    source /home/ashwink/Documents/swms/.venv/bin/activate
    python main_project/eval/epoch11_frame200_cosine_sim.py
"""

import os
import pickle
import sys

import imageio.v2 as imageio
import numpy as np
import open_clip
import torch
import torch.nn.functional as F
from PIL import Image

MAIN_PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_ROOT = os.path.dirname(MAIN_PROJECT_DIR)
sys.path.insert(0, REPO_ROOT)
sys.path.insert(0, os.path.join(MAIN_PROJECT_DIR, "caching"))

from cache_zhard import build_hard_neg_data, encode_strings  # noqa: E402
from swm.utils.envs import get_lang_table_env  # noqa: E402

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
ROLLOUT_DIR = os.path.join(
    MAIN_PROJECT_DIR, "rollouts_5_per", "expert+subopt_iters1000_exec8_with_pkls", "epoch11"
)
STEM = "epoch11_rollout0"
VIDEO_PATH = os.path.join(ROLLOUT_DIR, f"{STEM}_success.mp4")
STATES_PATH = os.path.join(ROLLOUT_DIR, f"{STEM}_pybullet_states.pkl")
ORACLE_CHUNKS_PATH = os.path.join(ROLLOUT_DIR, f"{STEM}_oracle_chunks.pkl")

CKPT_PATH = os.path.join(
    MAIN_PROJECT_DIR, "training", "checkpoints_clip_full_fine-tuned_with_subopt_data", "epoch_011.pt"
)

FRAME_T = 208
TRUE_STATEMENT = "The green cube is touching the blue moon. The peg is touching the green cube."
TOUCH_THRESH = 0.05  # matches cache_zhard.py

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
OUT_PATH = os.path.join(MAIN_PROJECT_DIR, "eval", "epoch11_frame208_cosine_sim_summary.txt")


def main():
    # -----------------------------------------------------------------
    # 1. Ground-truth block/peg positions at t=200, from this rollout's own
    #    saved pybullet state (not assumed).
    # -----------------------------------------------------------------
    with open(ORACLE_CHUNKS_PATH, "rb") as f:
        meta = pickle.load(f)["meta"]
    start_block, target_block = meta["start_block"], meta["target_block"]
    print(f"block_combo = [{start_block}, {target_block}]")

    with open(STATES_PATH, "rb") as f:
        pybullet_states = pickle.load(f)
    n_states = len(pybullet_states)
    if FRAME_T >= n_states:
        raise ValueError(f"FRAME_T={FRAME_T} >= n_states={n_states}")

    print("Initializing LangTable env and restoring pybullet state at t=%d ..." % FRAME_T)
    env = get_lang_table_env({"ood": False, "block_combo": [start_block, target_block]}, seed=42)
    inner = env.env
    inner.set_pybullet_state(pybullet_states[FRAME_T])

    blocks_now = inner.get_block_states()  # dict: block_name -> (2,); also has 'peg' (TARGET, not achieved)
    fk = inner._robot.forward_kinematics()
    achieved_peg_xy = np.asarray(fk.translation[:2], dtype=np.float32)

    dist_ab = float(np.linalg.norm(blocks_now[start_block] - blocks_now[target_block]))
    dist_peg_start = float(np.linalg.norm(achieved_peg_xy - blocks_now[start_block]))
    ab_touching = dist_ab < TOUCH_THRESH
    peg_touching = dist_peg_start < TOUCH_THRESH
    print(f"  dist({start_block}, {target_block}) = {dist_ab:.4f}  (touching={ab_touching})")
    print(f"  dist(peg, {start_block})            = {dist_peg_start:.4f}  (touching={peg_touching})")

    # -----------------------------------------------------------------
    # 2. 448 false statements, generated by cache_zhard.py's own logic,
    #    unmodified, applied to this single restored timestep.
    # -----------------------------------------------------------------
    fake_ep = {
        "block_states": [blocks_now],
        "actual_peg_positions": np.array([achieved_peg_xy], dtype=np.float32),
    }
    unique_strings, neg_indices = build_hard_neg_data(fake_ep)
    assert len(unique_strings) == 448, f"expected 448 unique negatives, got {len(unique_strings)}"
    print(f"Generated {len(unique_strings)} false statements at t={FRAME_T}.\n")

    # -----------------------------------------------------------------
    # 3. Load the epoch_011 fine-tuned CLIP checkpoint (both towers).
    # -----------------------------------------------------------------
    print(f"Loading checkpoint {CKPT_PATH} ...")
    ckpt = torch.load(CKPT_PATH, map_location=DEVICE)
    print(f"  epoch={ckpt['epoch']}  step={ckpt.get('step', '?')}")

    clip_model, _, preprocess = open_clip.create_model_and_transforms(
        "ViT-L-14", pretrained="datacomp_xl_s13b_b90k"
    )
    clip_model = clip_model.to(DEVICE)
    clip_model.load_state_dict(ckpt["clip_state_dict"])
    clip_model.eval()
    tokenizer = open_clip.get_tokenizer("ViT-L-14")

    # -----------------------------------------------------------------
    # 4. Encode the frame and all 449 statements (true + 448 false).
    # -----------------------------------------------------------------
    print(f"Reading frame {FRAME_T} from {VIDEO_PATH} ...")
    reader = imageio.get_reader(VIDEO_PATH)
    frame_np = reader.get_data(FRAME_T)  # (H, W, 3) uint8 RGB
    with torch.no_grad():
        img_t = preprocess(Image.fromarray(frame_np)).unsqueeze(0).to(DEVICE)
        z_img = F.normalize(clip_model.encode_image(img_t), dim=-1).squeeze(0).cpu().numpy()  # (768,)

    all_strings = [TRUE_STATEMENT] + unique_strings
    z_all = encode_strings(all_strings, clip_model, tokenizer, DEVICE)  # (449, 768)
    z_true = z_all[0]
    z_negs = z_all[1:]

    cos_true = float(z_img @ z_true)
    cos_negs = z_img @ z_negs.T  # (448,)

    # -----------------------------------------------------------------
    # 5. Rank and summarize.
    # -----------------------------------------------------------------
    all_cos = np.concatenate([[cos_true], cos_negs])
    order = np.argsort(-all_cos)  # descending
    rank_of_true = int(np.where(order == 0)[0][0]) + 1  # 1-indexed

    neg_order = np.argsort(-cos_negs)
    top10 = [(unique_strings[i], float(cos_negs[i])) for i in neg_order[:10]]

    lines = []
    lines.append("=== Epoch 11 fine-tuned CLIP: frame-200 cosine-sim check ===")
    lines.append(f"Checkpoint: {CKPT_PATH} (epoch={ckpt['epoch']}, step={ckpt.get('step', '?')})")
    lines.append(f"Video: {VIDEO_PATH}")
    lines.append(f"Frame: t={FRAME_T}")
    lines.append("")
    lines.append(f"Ground truth at t={FRAME_T} (from restored pybullet state):")
    lines.append(f"  dist({start_block}, {target_block}) = {dist_ab:.4f}  (touching={ab_touching}, thresh={TOUCH_THRESH})")
    lines.append(f"  dist(peg, {start_block})            = {dist_peg_start:.4f}  (touching={peg_touching})")
    lines.append(f"  TRUE_STATEMENT given holds at this frame: {ab_touching and peg_touching}")
    lines.append("")
    lines.append(f"True statement: \"{TRUE_STATEMENT}\"")
    lines.append(f"  cos_sim(z_img, z_true) = {cos_true:.4f}")
    lines.append("")
    lines.append(f"448 false statements (56 ordered pairs x 8 peg-blocks, inverted wording):")
    lines.append(f"  min={cos_negs.min():.4f}  mean={cos_negs.mean():.4f}  max={cos_negs.max():.4f}  std={cos_negs.std():.4f}")
    lines.append("")
    lines.append(f"Rank of true statement among all 449 (true + 448 false), by cosine sim descending: "
                  f"{rank_of_true} / 449  ({'TOP-1 / correct' if rank_of_true == 1 else 'NOT top-1'})")
    lines.append("")
    lines.append("Top-10 highest-scoring false statements (most confused with truth):")
    for s, c in top10:
        lines.append(f"  {c:.4f}  \"{s}\"")
    lines.append("")
    lines.append("All 448 false statements, sorted by cosine sim (descending):")
    for i in neg_order:
        lines.append(f"  {cos_negs[i]:.4f}  \"{unique_strings[i]}\"")

    summary = "\n".join(lines)
    with open(OUT_PATH, "w") as f:
        f.write(summary + "\n")

    print()
    print("\n".join(lines[:20]))
    print(f"\n... full breakdown written to {OUT_PATH}")


if __name__ == "__main__":
    main()
